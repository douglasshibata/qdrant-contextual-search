"""
Dynamic Hybrid Search Engine using Qdrant.
Combines Dense Semantic Vector Search and Sparse Lexical Vector Search
using dynamic weights generated by the LLM Query Analyzer, followed by Cross-Encoder Reranking.
"""

import logging
from typing import List, Dict, Any, Optional
from qdrant_client import QdrantClient, models

try:
    from .config import SearchEngineConfig, default_config
    from .embeddings import HybridEmbedder
    from .query_router import LLMQueryAnalyzer, QueryAnalysisResult
    from .reranker import CrossEncoderReranker
except ImportError:
    from config import SearchEngineConfig, default_config
    from embeddings import HybridEmbedder
    from query_router import LLMQueryAnalyzer, QueryAnalysisResult
    from reranker import CrossEncoderReranker

logger = logging.getLogger("QdrantHybridSearchEngine")
logging.basicConfig(level=logging.INFO)


class QdrantHybridSearchEngine:
    """
    Search Engine orchestrator combining:
    1. LLM Query Analysis (Context Router)
    2. Dual Embedding Generation (Dense + Sparse)
    3. Multi-Vector Qdrant Search with Dynamic Weighted Fusion
    4. Cross-Encoder Reranking
    """

    def __init__(
        self,
        client: Optional[QdrantClient] = None,
        embedder: Optional[HybridEmbedder] = None,
        router: Optional[LLMQueryAnalyzer] = None,
        reranker: Optional[CrossEncoderReranker] = None,
        config: Optional[SearchEngineConfig] = None,
    ) -> None:
        self.config = config or default_config
        self.embedder = embedder or HybridEmbedder(config=self.config)
        self.router = router or LLMQueryAnalyzer(config=self.config)
        self.reranker = reranker or CrossEncoderReranker(config=self.config)

        if client is not None:
            self.client = client
        else:
            if self.config.qdrant_url == ":memory:":
                self.client = QdrantClient(":memory:")
            else:
                self.client = QdrantClient(
                    url=self.config.qdrant_url,
                    api_key=self.config.qdrant_api_key
                )

    def search(
        self,
        query: str,
        top_k_retrieval: Optional[int] = None,
        top_k_rerank: Optional[int] = None,
    ) -> Dict[str, Any]:
        """
        Executes end-to-end hybrid contextual search:
        - Analyzes query intent to define dense_weight vs sparse_weight
        - Embeds query into Dense and Sparse vectors
        - Runs Qdrant hybrid retrieval with score fusion
        - Cross-Encoder reranks top candidates
        """
        k_retrieval = top_k_retrieval or self.config.top_k_retrieval
        k_rerank = top_k_rerank or self.config.top_k_rerank

        logger.info(f"--- Starting Hybrid Search for Query: '{query}' ---")

        # Step 1: LLM Query Analyzer (Define Weights)
        analysis: QueryAnalysisResult = self.router.analyze(query)
        logger.info(
            f"Query Router -> Intent: '{analysis.intent_type}' | "
            f"Dense Weight: {analysis.dense_weight:.2f} | "
            f"Sparse Weight: {analysis.sparse_weight:.2f}"
        )

        # Step 2: Generate Query Embeddings
        dense_q, sparse_q = self.embedder.embed_single(query)

        col_name = self.config.collection_name

        # Step 3: Qdrant Retrieval for Dense and Sparse Vectors
        dense_res = self.client.query_points(
            collection_name=col_name,
            query=dense_q,
            using=self.config.dense_vector_name,
            limit=k_retrieval
        )
        dense_hits = dense_res.points

        sparse_res = self.client.query_points(
            collection_name=col_name,
            query=sparse_q,
            using=self.config.sparse_vector_name,
            limit=k_retrieval
        )
        sparse_hits = sparse_res.points

        # Step 4: Dynamic Weighted Score Fusion
        candidate_map: Dict[Any, Dict[str, Any]] = {}

        # Normalize dense scores
        dense_scores = [h.score for h in dense_hits]
        max_d = max(dense_scores) if dense_scores else 1.0
        min_d = min(dense_scores) if dense_scores else 0.0
        range_d = (max_d - min_d) if (max_d - min_d) > 1e-6 else 1.0

        for h in dense_hits:
            norm_score = (h.score - min_d) / range_d
            candidate_map[h.id] = {
                "id": h.id,
                "payload": h.payload or {},
                "content": h.payload.get("content", "") if h.payload else "",
                "dense_score": float(h.score),
                "norm_dense": float(norm_score),
                "sparse_score": 0.0,
                "norm_sparse": 0.0,
            }

        # Normalize sparse scores
        sparse_scores = [h.score for h in sparse_hits]
        max_s = max(sparse_scores) if sparse_scores else 1.0
        min_s = min(sparse_scores) if sparse_scores else 0.0
        range_s = (max_s - min_s) if (max_s - min_s) > 1e-6 else 1.0

        for h in sparse_hits:
            norm_score = (h.score - min_s) / range_s
            if h.id not in candidate_map:
                candidate_map[h.id] = {
                    "id": h.id,
                    "payload": h.payload or {},
                    "content": h.payload.get("content", "") if h.payload else "",
                    "dense_score": 0.0,
                    "norm_dense": 0.0,
                    "sparse_score": float(h.score),
                    "norm_sparse": float(norm_score),
                }
            else:
                candidate_map[h.id]["sparse_score"] = float(h.score)
                candidate_map[h.id]["norm_sparse"] = float(norm_score)

        # Compute combined weighted score
        candidates: List[Dict[str, Any]] = []
        for cand in candidate_map.values():
            fusion_score = (
                analysis.dense_weight * cand["norm_dense"] +
                analysis.sparse_weight * cand["norm_sparse"]
            )
            cand["fusion_score"] = float(fusion_score)
            candidates.append(cand)

        # Sort candidates by fusion score
        candidates = sorted(candidates, key=lambda x: x["fusion_score"], reverse=True)[:k_retrieval]
        logger.info(f"Retrieved {len(candidates)} candidates after Weighted Score Fusion.")

        # Step 5: Cross-Encoder Reranking
        reranked_results = self.reranker.rerank(query, candidates, top_k=k_rerank)
        logger.info(f"Reranked top {len(reranked_results)} results using Cross-Encoder.")

        return {
            "query": query,
            "query_analysis": analysis,
            "total_candidates": len(candidates),
            "candidates": candidates,
            "reranked_results": reranked_results
        }


